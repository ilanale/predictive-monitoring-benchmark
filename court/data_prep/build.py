"""WS1 runner: raw inputs -> data/processed/court_phase{1,2,3}.{csv,parquet} + court_columns.json + data_report.md.

    python -m court.data_prep.build                 # full build
    python -m court.data_prep.build --sample 0.02   # dev: 2% of windowed cases -> data/interim/sample/
"""
import argparse
import json
import os
import resource
import shutil
import time

import numpy as np
import pandas as pd

from . import export, global_features, ingest, phase_fixes, prefix_features, segments


def build_tables(cases_all, ev_raw, report, sample=None, seed=0, log=print):
    """Pure in-memory build. cases_all: raw case table; ev_raw: events (case-table cases).

    Returns ({k: DataFrame}, column spec).
    """
    fixed_all, win = phase_fixes.apply_fixes(cases_all, report, log=log)
    if sample:
        win = win.sample(frac=sample, random_state=seed).reset_index(drop=True)
        report["sample_fraction"] = sample
    seg = segments.build_segments(win, report, log=log)
    case_index = pd.Index(win.ucid.values)
    ev = ev_raw[ev_raw.ucid.isin(case_index)]
    report["events_window_cases"] = int(len(ev))
    ev = segments.sort_events(ev, case_index)
    attr_flags = [c for c in ev.columns if c.startswith("attribute_") and c != "attribute_duplicates"]
    t0 = time.time()
    EF = prefix_features.event_features(ev, attr_flags)
    log(f"[prefix] event features {EF.shape} in {time.time() - t0:.1f}s")
    attr_cols = ["P_attr_duplicates"] + ["P_" + a.replace("attribute_", "attr_") for a in attr_flags]
    pp_dyn = ["PP_n_self_loops", "PP_n_return_loops", "PP_n_repeats", "PP_n_distinct_judges",
              "PP_events_last30", "PP_events_last90"]
    all_pos = pd.Index(fixed_all.ucid.values)
    tables, spec = {}, None
    for k in (1, 2, 3):
        sk = seg[seg.phase == k].reset_index(drop=True)
        sk, ev_idx, seg_idx = segments.build_traces(sk, ev, case_index, report, phase=k, log=log)
        t0 = time.time()
        q_case = all_pos.get_indexer(sk.ucid.values)[seg_idx]
        G = global_features.global_features(fixed_all, q_case, ev.d.values[ev_idx], np.full(len(ev_idx), k))
        log(f"[global] phase {k}: {G.shape} in {time.time() - t0:.1f}s")
        df = export.assemble_phase(k, sk, ev_idx, seg_idx, ev, EF, G, win, attr_cols, pp_dyn)
        del G
        rr = report.setdefault("rare_levels_to_other", {}).setdefault(f"p{k}", {})
        df = export.rare_to_other(df, ["M_" + c for c in export.M_CAT], ["Activity", "judge"], rr)
        spec_k = export.column_spec(df, attr_cols, pp_dyn)
        spec = spec or spec_k
        assert spec_k["views"] == spec["views"]
        _phase_stats(k, sk, df, report)
        tables[k] = df
    return tables, spec


def _phase_stats(k, sk, df, report):
    q = [0.1, 0.25, 0.5, 0.75, 0.9, 0.99]
    pos = sk[sk.label01 == 1]
    report.setdefault("phases", {})[f"p{k}"] = {
        "segments": int(len(sk)), "rows": int(len(df)), "in_phase_rows": int(df.in_phase.sum()),
        "label_rate_deviant": float(sk.label01.mean()) if len(sk) else None,
        "n_deviant": int(sk.label01.sum()),
        "in_phase_len_quantiles": {str(x): float(sk.n_in_phase.quantile(x)) for x in q},
        "in_phase_len_q90_positive": float(pos.n_in_phase.quantile(0.9)) if len(pos) else None,
        "n_hist_quantiles": {str(x): float(sk.n_hist.quantile(x)) for x in q},
        "phase_days_quantiles": {str(x): float((sk.exit - sk.entry).quantile(x)) for x in q},
        "remaining_in_phase_quantiles_in_phase_rows": {
            str(x): float(df.remaining_in_phase[df.in_phase == 1].quantile(x)) for x in q},
        "n_columns": int(df.shape[1]),
    }


