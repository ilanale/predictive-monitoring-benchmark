def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sample", type=float, default=None)
    ap.add_argument("--data", default="data")
    ap.add_argument("--repo-report", default="docs/data_report.md")
    a = ap.parse_args()
    t0 = time.time()
    raw, interim = os.path.join(a.data, "raw"), os.path.join(a.data, "interim")
    out = os.path.join(interim, "sample") if a.sample else os.path.join(a.data, "processed")
    os.makedirs(out, exist_ok=True)
    report = {"generated": time.strftime("%Y-%m-%d %H:%M %Z")}
    cases, ev, report = ingest.run(raw, interim, report=report)
    tables, spec = build_tables(cases, ev, report, sample=a.sample)
    del ev
    report["outputs"] = {}
    for k, df in tables.items():
        base = os.path.join(out, f"court_phase{k}")
        cs, ps = export.write_phase(df, base)
        report["outputs"][f"court_phase{k}.csv"] = {"rows": f"{len(df):,}", "size": cs}
        report["outputs"][f"court_phase{k}.parquet"] = {"rows": f"{len(df):,}", "size": ps}
        print(f"[export] phase {k}: {df.shape} csv {cs/1e6:.0f} MB parquet {ps/1e6:.0f} MB")
    export.write_columns_json(spec, os.path.join(out, "court_columns.json"))
    report["outputs"]["court_columns.json"] = {"size": os.path.getsize(os.path.join(out, "court_columns.json"))}
    report["runtime_s"] = time.time() - t0
    report["peak_rss_gb"] = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1e9  # bytes on macOS
    json.dump(report, open(os.path.join(out, "data_report.json"), "w"), indent=1, default=str)
    write_report(report, spec, os.path.join(out, "data_report.md"))
    if not a.sample and a.repo_report:
        os.makedirs(os.path.dirname(a.repo_report), exist_ok=True)
        shutil.copy(os.path.join(out, "data_report.md"), a.repo_report)
    print(f"[build] done in {report['runtime_s']:.0f}s, peak RSS {report['peak_rss_gb']:.2f} GB -> {out}")


if __name__ == "__main__":
    main()
